import { testID } from './ids';
import { act, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import { api, ApiError } from '../src/api/client';
import type { AgentAccount, Conversation, Participant } from '../src/api/types';
import { App } from '../src/app/App';

const human: Participant = { participant_id: testID(1), kind: 'human', name: '用户', created_at: 1 };
const agent: AgentAccount = { participant_id: testID(2), kind: 'agent', name: 'Mia', username: 'mia.test', owner_participant_id: testID(1), created_at: 2 };
const newcomer: AgentAccount = { participant_id: testID(3), kind: 'agent', name: 'Nova', username: 'nova.test', owner_participant_id: testID(1), created_at: 3 };
const participant = (value: AgentAccount): Participant => ({ participant_id: value.participant_id, kind: 'agent', name: value.name, created_at: value.created_at });
const group: Conversation = { conversation_id: testID(11), kind: 'group', title: '项目组', created_at: 11, dissolved_at: null, hidden: false };
const direct: Conversation = { conversation_id: testID(12), kind: 'direct', title: null, created_at: 10, dissolved_at: null, hidden: false };
function basic() {
  vi.spyOn(api, 'me').mockResolvedValue(human);
  vi.spyOn(api, 'participants').mockResolvedValue([human, participant(agent)]);
  vi.spyOn(api, 'conversations').mockResolvedValue([group, direct]);
  vi.spyOn(api, 'members').mockResolvedValue([human, participant(agent)]);
  vi.spyOn(api, 'getConversation').mockImplementation(async (id) => id === testID(11) ? group : direct);
  vi.spyOn(api, 'messages').mockImplementation(async (id) => ({ messages: [{ message_seq: 1, message_id: id, conversation_id: id, sender_id: testID(2), content: '原有消息', created_at: 100, mentioned_agent_ids: [], quoted_message_id: null }], has_more: false }));
}
async function openManager(user: ReturnType<typeof userEvent.setup>) {
  await user.click(await screen.findByRole('button', { name: '通讯录' }));
  await user.click(screen.getByRole('button', { name: '管理我的 Agent' }));
  return await screen.findByRole('dialog', { name: '我的 Agent' });
}

describe('Agent management', () => {
  it('creates an owned Agent and updates contacts and group candidates', async () => {
    basic(); vi.spyOn(api, 'agents').mockResolvedValue([agent]);
    const create = vi.spyOn(api, 'createAgent').mockResolvedValue(newcomer);
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user);
    await within(manager).findByText('mia.test');
    await user.click(within(manager).getByRole('button', { name: '创建 Agent' }));
    const dialog = screen.getByRole('dialog', { name: '创建 Agent' });
    expect(document.activeElement).toBe(within(dialog).getByLabelText('Agent 名称'));
    await user.type(within(dialog).getByLabelText('Agent 名称'), 'Nova');
    await user.type(within(dialog).getByLabelText('登录账号'), 'nova.test');
    await user.type(within(dialog).getByLabelText('密码'), 'fixture-pass');
    await user.click(within(dialog).getByRole('button', { name: '创建 Agent' }));
    await waitFor(() => expect(create).toHaveBeenCalledWith({ name: 'Nova', username: 'nova.test', password: 'fixture-pass' }));
    expect(await screen.findByText('nova.test')).toBeTruthy();
    expect(document.activeElement).toBe(screen.getByRole('button', { name: '创建 Agent' }));
    expect(screen.queryByDisplayValue('fixture-pass')).toBeNull();
    await user.click(screen.getByRole('button', { name: '关闭' }));
    expect(screen.getByRole('button', { name: /Nova.*点击发起对话/ })).toBeTruthy();
    await user.click(screen.getByRole('button', { name: '消息' }));
    await user.click(screen.getByRole('button', { name: '创建群聊' }));
    expect(within(screen.getByRole('dialog', { name: '创建群聊' })).getByRole('checkbox', { name: 'Nova' })).toBeTruthy();
  });
  it('refreshes names everywhere without losing the selected conversation, quote or blue mention draft', async () => {
    basic(); vi.spyOn(api, 'agents').mockResolvedValue([agent]);
    const renamed = { ...agent, name: 'Mia 新名', username: 'mia.new' };
    const update = vi.spyOn(api, 'updateAgent').mockResolvedValue(renamed);
    const user = userEvent.setup(); render(<App />);
    await screen.findByText('原有消息');
    await user.click(await screen.findByRole('button', { name: new RegExp(`^单聊 #${testID(12)}`) }));
    await waitFor(() => expect(screen.getByRole('button', { name: /Mia.*单聊/ })).toBeTruthy());
    await user.click(screen.getByRole('button', { name: /项目组.*群聊/ }));
    await screen.findByText('原有消息');
    await user.click(screen.getByRole('button', { name: `引用消息 ${testID(11)}` }));
    const input = screen.getByRole('textbox', { name: '消息内容' }) as HTMLTextAreaElement;
    await user.type(input, '@Mia'); await user.keyboard('{Enter}'); await user.type(input, '草稿保留');
    const manager = await openManager(user);
    await user.click(await within(manager).findByRole('button', { name: /编辑 Mia/ }));
    const dialog = screen.getByRole('dialog', { name: '编辑 Agent' });
    const name = within(dialog).getByLabelText('Agent 名称'); const username = within(dialog).getByLabelText('登录账号');
    await user.clear(name); await user.type(name, 'Mia 新名');
    await user.clear(username); await user.type(username, 'mia.new');
    await user.click(within(dialog).getByRole('button', { name: '保存修改' }));
    await waitFor(() => expect(update).toHaveBeenCalledWith(testID(2), { name: 'Mia 新名', username: 'mia.new' }));
    await user.click(screen.getByRole('button', { name: '关闭' }));
    expect(screen.getByRole('button', { name: /Mia 新名.*点击发起对话/ })).toBeTruthy();
    expect(input.value).toBe('@Mia 草稿保留');
    expect(document.querySelector('.mention-highlight')?.textContent).toBe('@Mia');
    expect(screen.getByRole('button', { name: '取消引用' })).toBeTruthy();
    await user.click(screen.getByRole('button', { name: '消息' }));
    expect(screen.getByRole('button', { name: /Mia 新名.*单聊/ })).toBeTruthy();
    await user.click(screen.getByRole('button', { name: '查看会话详情' }));
    expect(within(screen.getByRole('complementary', { name: '群聊详情' })).getByText('Mia 新名')).toBeTruthy();
    await user.click(screen.getByRole('button', { name: '创建群聊' }));
    expect(within(screen.getByRole('dialog', { name: '创建群聊' })).getByRole('checkbox', { name: 'Mia 新名' })).toBeTruthy();
  });
  it('resets a password without sending unchanged fields or displaying the password afterwards', async () => {
    basic(); vi.spyOn(api, 'agents').mockResolvedValue([agent]);
    const update = vi.spyOn(api, 'updateAgent').mockResolvedValue(agent);
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user);
    await user.click(await within(manager).findByRole('button', { name: /编辑 Mia/ }));
    let dialog = screen.getByRole('dialog', { name: '编辑 Agent' });
    await user.type(within(dialog).getByLabelText('新密码（可留空）'), 'test-reset-password');
    await user.click(within(dialog).getByRole('button', { name: '保存修改' }));
    await waitFor(() => expect(update).toHaveBeenCalledWith(testID(2), { password: 'test-reset-password' }));
    await user.click(await screen.findByRole('button', { name: /编辑 Mia/ }));
    dialog = screen.getByRole('dialog', { name: '编辑 Agent' });
    expect((within(dialog).getByLabelText('新密码（可留空）') as HTMLInputElement).value).toBe('');
  });
  it('shows a conflict without retrying a write or exposing the password', async () => {
    basic(); vi.spyOn(api, 'agents').mockResolvedValue([]);
    const create = vi.spyOn(api, 'createAgent').mockRejectedValue(new ApiError('conflict', 'CONFLICT', 409));
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user);
    await waitFor(() => expect((within(manager).getByRole('button', { name: '创建 Agent' }) as HTMLButtonElement).disabled).toBe(false));
    await user.click(within(manager).getByRole('button', { name: '创建 Agent' }));
    const dialog = screen.getByRole('dialog', { name: '创建 Agent' });
    await user.type(within(dialog).getByLabelText('Agent 名称'), 'Nova');
    await user.type(within(dialog).getByLabelText('登录账号'), 'nova.test');
    const password = within(dialog).getByLabelText('密码') as HTMLInputElement;
    await user.type(password, 'fixture-pass');
    await user.click(within(dialog).getByRole('button', { name: '创建 Agent' }));
    expect(await within(dialog).findByText('该登录账号已被使用，请换一个账号。')).toBeTruthy();
    expect(password.type).toBe('password');
    expect(create).toHaveBeenCalledTimes(1);
  });
  it('does not allow creation while the initial list request is pending', async () => {
    basic();
    let finish!: (value: AgentAccount[]) => void;
    vi.spyOn(api, 'agents').mockImplementation(() => new Promise((resolve) => { finish = resolve; }));
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user);
    expect((within(manager).getByRole('button', { name: '创建 Agent' }) as HTMLButtonElement).disabled).toBe(true);
    await act(async () => finish([agent]));
    expect((within(manager).getByRole('button', { name: '创建 Agent' }) as HTMLButtonElement).disabled).toBe(false);
  });
  it('filters other owners, shows loading errors and retries without creating accounts', async () => {
    basic();
    const foreign = { ...newcomer, owner_participant_id: testID(99), name: '其他人的 Agent' };
    const list = vi.spyOn(api, 'agents').mockRejectedValueOnce(new Error('连接失败')).mockResolvedValueOnce([agent, foreign]);
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user);
    expect(await within(manager).findByText('连接失败')).toBeTruthy();
    await user.click(within(manager).getByRole('button', { name: '重试' }));
    expect(await within(manager).findByText('mia.test')).toBeTruthy();
    expect(within(manager).queryByText('其他人的 Agent')).toBeNull();
    expect(list).toHaveBeenCalledTimes(2);
  });
  it('aborts and ignores an old owner response during identity changes', async () => {
    basic();
    const nextHuman: Participant = { participant_id: testID(10), kind: 'human', name: '另一用户', created_at: 1 };
    let notify!: () => void; let finishOld!: (value: AgentAccount[]) => void; let oldSignal: AbortSignal | undefined;
    vi.spyOn(api, 'onUnauthorized').mockImplementation((listener) => { notify = listener; return () => {}; });
    vi.spyOn(api, 'agents').mockImplementationOnce((signal) => { oldSignal = signal; return new Promise((resolve) => { finishOld = resolve; }); }).mockResolvedValueOnce([{ ...newcomer, owner_participant_id: testID(10) }]);
    vi.spyOn(api, 'login').mockResolvedValue({ participant: nextHuman, expires_at: 1800000000000 });
    vi.mocked(api.participants).mockResolvedValueOnce([human, participant(agent)]).mockResolvedValueOnce([nextHuman, participant(newcomer)]);
    const user = userEvent.setup(); render(<App />);
    await openManager(user); await waitFor(() => expect(finishOld).toBeTypeOf('function'));
    act(() => { void api.suspendSession(); notify(); });
    await user.type(await screen.findByLabelText('账号'), 'otheruser'); await user.type(screen.getByLabelText('密码'), 'fixture-pass');
    await user.click(screen.getByRole('button', { name: '登录' }));
    await waitFor(() => expect(oldSignal?.aborted).toBe(true));
    await act(async () => finishOld([agent]));
    const nextManager = await openManager(user);
    expect(await within(nextManager).findByText('nova.test')).toBeTruthy();
    expect(within(nextManager).queryByText('mia.test')).toBeNull();
  });
  it('does not apply a pending creation after the signed-in identity changes', async () => {
    basic();
    const nextHuman: Participant = { participant_id: testID(10), kind: 'human', name: '另一用户', created_at: 1 };
    let notify!: () => void; let finishCreate!: (value: AgentAccount) => void;
    vi.spyOn(api, 'onUnauthorized').mockImplementation((listener) => { notify = listener; return () => {}; });
    vi.spyOn(api, 'agents').mockResolvedValue([agent]);
    vi.spyOn(api, 'createAgent').mockImplementation(() => new Promise((resolve) => { finishCreate = resolve; }));
    vi.spyOn(api, 'login').mockResolvedValue({ participant: nextHuman, expires_at: 1800000000000 });
    vi.mocked(api.participants).mockResolvedValueOnce([human, participant(agent)]).mockResolvedValueOnce([nextHuman]);
    const user = userEvent.setup(); render(<App />);
    const manager = await openManager(user); await within(manager).findByText('mia.test');
    await user.click(within(manager).getByRole('button', { name: '创建 Agent' }));
    const dialog = screen.getByRole('dialog', { name: '创建 Agent' });
    await user.type(within(dialog).getByLabelText('Agent 名称'), 'Nova');
    await user.type(within(dialog).getByLabelText('登录账号'), 'nova.test');
    await user.type(within(dialog).getByLabelText('密码'), 'fixture-pass');
    await user.click(within(dialog).getByRole('button', { name: '创建 Agent' }));
    act(() => { void api.suspendSession(); notify(); });
    await user.type(await screen.findByLabelText('账号'), 'otheruser'); await user.type(screen.getByLabelText('密码'), 'fixture-pass');
    await user.click(screen.getByRole('button', { name: '登录' }));
    await waitFor(() => expect(screen.queryByRole('dialog', { name: '创建 Agent' })).toBeNull());
    await act(async () => finishCreate(newcomer));
    await user.click(await screen.findByRole('button', { name: '通讯录' }));
    expect(screen.queryByRole('button', { name: /Nova.*点击发起对话/ })).toBeNull();
  });
  it('does not show the management entry for an Agent identity', async () => {
    basic(); vi.mocked(api.me).mockResolvedValue(participant(agent));
    const user = userEvent.setup(); render(<App />);
    await user.click(await screen.findByRole('button', { name: '通讯录' }));
    expect(screen.queryByRole('button', { name: '管理我的 Agent' })).toBeNull();
  });
});
